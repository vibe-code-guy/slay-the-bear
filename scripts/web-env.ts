// Write apps/web/.env.local for running the web app against a testnet game, with the relayer,
// keeper and villager keys read from ~/.near-credentials. The file is gitignored.
//   npx tsx scripts/web-env.ts --game dev3.slaythebear.testnet
// For a hosted deployment, set the same variables in the host's secret settings instead.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { VILLAGERS } from "../packages/agents/src/index";
import { REPO_ROOT, arg, hasKey, loadKey } from "./lib/near";

const game = arg("game");
const root = arg("root", "slaythebear.testnet");
const keeper = `keeper.${root}`;
const villagers: Record<string, string> = {};
for (const v of VILLAGERS) {
  const id = `${v.prefix}.${root}`;
  if (hasKey(id)) villagers[id] = loadKey(id).toString();
}
const lines = [
  "# Generated by scripts/web-env.ts. Contains private keys of throwaway testnet accounts. Never commit.",
  `NEXT_PUBLIC_GAME_ID=${game}`,
  `NEXT_PUBLIC_ROOT_ACCOUNT=${root}`,
  "NEXT_PUBLIC_RPC_URL=https://rpc.testnet.fastnear.com",
  `RELAYER_ACCOUNT_ID=${root}`,
  `RELAYER_PRIVATE_KEY=${loadKey(root).toString()}`,
  hasKey(keeper) ? `KEEPER_ACCOUNT_ID=${keeper}` : "",
  hasKey(keeper) ? `KEEPER_PRIVATE_KEY=${loadKey(keeper).toString()}` : "",
  `VILLAGER_KEYS=${JSON.stringify(villagers)}`,
  "GUEST_FUND_NEAR=0.01",
].filter(Boolean);
const path = join(REPO_ROOT, "apps", "web", ".env.local");
writeFileSync(path, lines.join("\n") + "\n", { mode: 0o600 });
console.log(`wrote ${path} for ${game} (${Object.keys(villagers).length} villagers${hasKey(keeper) ? ", keeper" : ""})`);
